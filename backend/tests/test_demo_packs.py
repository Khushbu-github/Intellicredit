def test_strong_borrower_is_approved(client, auth_headers, demo_packs):
    case_id = _new_case(client, auth_headers, "Vishwakarma Steel Ltd")
    _upload_pack(client, case_id, auth_headers, demo_packs / "strong_borrower")
    case = client.get(f"/api/applications/{case_id}/analysis", headers=auth_headers).json()

    assert case["decision"] == "APPROVE", case["decision_reason"]
    assert case["recommended_limit_cr"] is not None
    assert case["spread"].startswith("Repo +")
    assert case["bounce_count"] == 0
    assert not any(g["breached"] and g["severity"] == "critical" for g in case["raw_data"]["gates"])


def test_thin_file_borrower_is_referred_not_rejected(client, auth_headers, demo_packs):
    """
    Missing paperwork is not misconduct. A borrower whose file is too thin to
    size a limit must be referred for more evidence, never rejected outright.
    """
    case_id = _new_case(client, auth_headers, "Meghna Textiles Pvt Ltd")
    _upload_pack(client, case_id, auth_headers, demo_packs / "thin_file_borrower")
    case = client.get(f"/api/applications/{case_id}/analysis", headers=auth_headers).json()

    assert case["decision"] == "REFER", case["decision_reason"]
    assert case["recommended_limit_cr"] is None
    assert case["raw_data"]["evidence_coverage"] < 100


def test_distressed_borrower_is_rejected(client, auth_headers, demo_packs):
    case_id = _new_case(client, auth_headers, "Ashwin Infra Ltd")
    _upload_pack(client, case_id, auth_headers, demo_packs / "distressed_borrower")
    case = client.get(f"/api/applications/{case_id}/analysis", headers=auth_headers).json()

    assert case["decision"] == "REJECT", case["decision_reason"]
    assert case["recommended_limit_cr"] is None
    assert case["spread"] == "Not priced"


def test_distressed_borrower_trips_every_screening_signal(client, auth_headers, demo_packs):
    """The pack exists to exercise the checks; this asserts each one fired."""
    case_id = _new_case(client, auth_headers, "Ashwin Infra Ltd")
    _upload_pack(client, case_id, auth_headers, demo_packs / "distressed_borrower")
    case = client.get(f"/api/applications/{case_id}/analysis", headers=auth_headers).json()

    assert case["bounce_count"] >= 2, "cheque returns not detected"
    assert case["gst_circular_trading_pct"] > 20, "circular trading not detected"
    assert case["gst_turnover_mismatch_pct"] > 25, "ITR/GST turnover gap not detected"
    assert case["litigation_count"] >= 1, "NI Act matter not detected"
    assert case["promoter_pledge"] > 0.5, "promoter pledge not detected"
    assert case["related_party_flag"] is True, "related-party dealings not detected"

    codes = {flag["code"] for flag in case["red_flags"]}
    for expected in ("GOING_CONCERN", "AUDIT_QUALIFIED", "PLEDGE_HIGH", "TURNOVER_MISMATCH"):
        assert expected in codes, f"{expected} missing from the flag register"


def test_the_three_packs_are_ordered_by_score(client, auth_headers, demo_packs):
    """Strong > thin file > distressed, or the packs no longer tell a story."""
    scores = {}
    for pack in ("strong_borrower", "thin_file_borrower", "distressed_borrower"):
        case_id = _new_case(client, auth_headers, pack)
        _upload_pack(client, case_id, auth_headers, demo_packs / pack)
        scores[pack] = client.get(
            f"/api/applications/{case_id}/analysis", headers=auth_headers
        ).json()["total_score"]

    assert scores["strong_borrower"] > scores["thin_file_borrower"] > scores["distressed_borrower"], scores


def test_a_demo_case_produces_a_downloadable_memo(client, auth_headers, demo_packs):
    case_id = _new_case(client, auth_headers, "Vishwakarma Steel Ltd")
    _upload_pack(client, case_id, auth_headers, demo_packs / "strong_borrower")

    response = client.get(f"/api/applications/{case_id}/cam", headers=auth_headers)
    assert response.status_code == 200
    assert response.content.startswith(b"PK")
    assert len(response.content) > 10_000, "the memo looks suspiciously empty"
