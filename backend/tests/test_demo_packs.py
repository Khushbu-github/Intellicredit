"""
The demo borrower packs, driven through the real HTTP API.

These are the fixtures a demonstration runs on, so they are tested like code:
if a scoring change flips the "strong" borrower to REJECT, or the upload
validation starts refusing the generated PDFs, the build fails rather than the
demo. That the packs are generated by a script and validated here is what makes
them trustworthy to show.
"""

import json
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "generate_demo_data.py"
BACKEND_ROOT = SCRIPT.parents[1]


@pytest.fixture(scope="module")
def demo_packs(tmp_path_factory) -> Path:
    """Generate the packs into a temp directory, exactly as the script does."""
    workdir = tmp_path_factory.mktemp("demo")
    result = subprocess.run(
        [sys.executable, str(SCRIPT)],
        cwd=workdir,
        capture_output=True,
        text=True,
        env={"PYTHONPATH": str(BACKEND_ROOT), "PATH": "", "SYSTEMROOT": ""},
    )
    assert result.returncode == 0, result.stderr
    return workdir / "samples"


def _upload_pack(client, case_id, headers, pack_dir: Path):
    files = [
        ("files", (path.name, path.read_bytes(), "application/octet-stream"))
        for path in sorted(pack_dir.iterdir())
        if path.is_file()
    ]
    return client.post(
        f"/api/applications/{case_id}/documents", files=files, headers=headers
    )


def _new_case(client, headers, name: str, sector: str = "Manufacturing") -> int:
    response = client.post(
        "/api/applications", json={"company_name": name, "sector": sector}, headers=headers
    )
    assert response.status_code == 201
    return response.json()["app_id"]


# ---------------------------------------------------------------------------
# The generated files must survive the upload validator
# ---------------------------------------------------------------------------

def test_generated_pdfs_are_real_pdfs(demo_packs):
    """
    A text file renamed .pdf is rejected by the upload endpoint's magic-byte
    check - which is correct, and is why the generator must emit real PDFs.
    """
    pdfs = list(demo_packs.rglob("*.pdf"))
    assert pdfs, "the generator produced no PDFs"
    for path in pdfs:
        assert path.read_bytes().startswith(b"%PDF-"), path.name


def test_generated_json_and_csv_are_well_formed(demo_packs):
    for path in demo_packs.rglob("*.json"):
        json.loads(path.read_text(encoding="utf-8"))
    for path in demo_packs.rglob("*.csv"):
        assert path.read_text(encoding="utf-8").strip(), path.name


def test_every_pack_uploads_and_parses_cleanly(client, auth_headers, demo_packs):
    for pack in sorted(demo_packs.iterdir()):
        case_id = _new_case(client, auth_headers, pack.name)
        response = _upload_pack(client, case_id, auth_headers, pack)

        assert response.status_code == 201, f"{pack.name}: {response.text}"
        body = response.json()

        failures = [i for i in body["ingested"] if i["parse_status"] == "failed"]
        assert not failures, f"{pack.name} had parse failures: {failures}"
        assert body["parsed_count"] == len(body["ingested"])


